T = []   # トークン
C = []   # 新カード

def ch(id, name, world, rarity, cost, atk, hp, kws=(), effects=(), armor=0, note="", art="", token=False, pay=None):
    d = dict(id=id, name=name, world=world, type="char", rarity=rarity, cost=cost, atk=atk, hp=hp,
             keywords=list(kws), effects=list(effects), armor=armor, note=note, artNote=art)
    if pay: d["pay"] = pay
    if token: d["token"] = True; d["limit"] = 0
    (T if token else C).append(d)

def sp(id, name, world, rarity, cost, effects, note="", art="", token=False):
    d = dict(id=id, name=name, world=world, type="spell", rarity=rarity, cost=cost, keywords=[], effects=list(effects), note=note, artNote=art)
    if token: d["token"] = True; d["limit"] = 0
    (T if token else C).append(d)

E = lambda kind, n=1, **k: dict(kind=kind, n=n, **k)

